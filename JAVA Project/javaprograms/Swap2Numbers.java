package javaprograms;

public class Swap2Numbers {

	public static void main(String[] args) {
		int a =10;
		int b= 20;
		System.out.println("Before swapping values are.."+a+" "+b);
		int c= a; //10
		
		a=b;  //a-20
		b=c;  // b-10
 
		System.out.println("After swapping values are.."+a+" "+b);
		
	}

}
