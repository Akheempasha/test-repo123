package javaprograms;

import java.util.Iterator;

public class PrintOneToHundred {

	public static void main(String[] args) {
		//Using ASCII values

     int one = 'A'/'A';   //65/65 = 1
     
     String s1 = "..........";
    
     for (int i = one; i <= (s1.length() * s1.length()); i++) {
    	 System.out.println(i);
		
	}
     
      //a = 97,b=98,c=99,d=100
     for (int i = one; i < 'd'; i++) {
    	 System.out.println(i);
		
	}
     
     
     
		
	}

}
